#!/bin/bash
# Unit test for finish-install.sh's fstab handling, against both fstab shapes
# an Omarchy install can have: the ISO's own writer (orchestrator
# phases_impl.py, _write_pre_mounted_fstab) and archinstall's genfstab.
#   bash test/fstab-test.sh payload/sp11-lcd/finish-install.sh
set -uo pipefail
# shellcheck source=/dev/null
source "${1:?usage: fstab-test.sh FINISH_INSTALL_SH}"
set +e
failures=0
expect() { # NAME EXPECTED ACTUAL
  if [[ $2 == "$3" ]]; then echo "PASS: $1"; else echo "FAIL: $1"; echo "  expected: $2"; echo "  actual:   $3"; failures=$((failures + 1)); fi
}
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

cat >"$tmp/iso" <<'EOF'
# /etc/fstab — generated by Omarchy ISO
# <device>  <mount>  <fs>  <options>  <dump>  <pass>
UUID=0b0c  /                      btrfs  noatime,compress=zstd,subvol=@       0 0
UUID=0b0c  /home                  btrfs  noatime,compress=zstd,subvol=@home   0 0
UUID=0b0c  /var/log               btrfs  noatime,compress=zstd,subvol=@log    0 0
UUID=0b0c  /var/cache/pacman/pkg  btrfs  noatime,compress=zstd,subvol=@pkg    0 0
UUID=AB12-CD34  /boot                   vfat   umask=0077              0 2
EOF

cat >"$tmp/genfstab" <<'EOF'
# Static information about the filesystems.
# /dev/mapper/omarchy_root
UUID=0b0c	/         	btrfs     	rw,relatime,compress=zstd:3,ssd,space_cache=v2,subvolid=256,subvol=/@	0 0

UUID=0b0c	/home     	btrfs     	rw,relatime,compress=zstd:3,ssd,space_cache=v2,subvolid=257,subvol=/@home	0 0
UUID=AB12-CD34      	/boot     	vfat      	rw,relatime,fmask=0077,dmask=0077,noauto,x-systemd.automount,x-systemd.idle-timeout=600	0 2
/swap/swapfile	none	swap	defaults	0 0
EOF

expect "ISO fstab: root subvolume" "@" "$(root_subvol "$tmp/iso")"
expect "genfstab: root subvolume" "/@" "$(root_subvol "$tmp/genfstab")"
expect "ISO fstab: everything but /" \
  "/home /var/log /var/cache/pacman/pkg /boot" "$(fstab_without_root "$tmp/iso" | awk '{print $2}' | xargs)"
expect "ISO fstab: ESP options kept" "umask=0077" "$(fstab_without_root "$tmp/iso" | awk '$2 == "/boot" {print $4}')"
expect "genfstab: everything but / and swap" "/home /boot" "$(fstab_without_root "$tmp/genfstab" | awk '{print $2}' | xargs)"
expect "genfstab: automount ESP mounted plainly" "rw,relatime,fmask=0077,dmask=0077" \
  "$(fstab_without_root "$tmp/genfstab" | awk '$2 == "/boot" {print $4}')"
# The filtered table must be one mount(8) reads: six fields per line.
expect "filtered lines have six fields" "" "$(fstab_without_root "$tmp/genfstab" | awk 'NF != 6')"

echo "failures: $failures"
exit $((failures > 0))
