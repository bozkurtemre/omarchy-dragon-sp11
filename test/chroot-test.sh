#!/bin/bash
# Exercise sp11-lcd inside the real target root image of the official ISO
# (omarchy-root.img.zst, a copy-on-write overlay: nothing is written to it).
# Run through test/chroot-test.ps1, after build-iso.ps1 staged the payload:
#   /in       official ISO      /payload  staged sp11-lcd/ (with firmware)
#   /build    build/            /test     test/       /work  scratch volume
#
# Covers what can be proven without the Surface: the device tree pin, the
# initramfs drop-in (built for the target kernel while the container runs
# another one), firmware installation through qcom-firmware-extract against
# the LCD device tree, and the UKI that the pinned uki.conf produces.
set -uo pipefail
version=${OMARCHY_VERSION:-4.5.0}
iso=/in/omarchy-$version-aarch64.iso
P=/payload/sp11-lcd
W=/work/chroot-test
failures=0
fail() { echo "FAIL: $*"; failures=$((failures + 1)); }
pass() { echo "PASS: $*"; }

bash /test/fstab-test.sh $P/finish-install.sh | grep -vE '^failures'
((PIPESTATUS[0] == 0)) || failures=$((failures + 1))

mkdir -p $W && cd $W
if [[ ! -f root.img ]]; then
  xorriso -osirrox on -indev "$iso" -extract /arch/aarch64/omarchy-root.img.zst root.img.zst >/dev/null 2>&1
  zstd -dq --rm root.img.zst -o root.img || { echo "cannot unpack the root image"; exit 2; }
fi
xorriso -osirrox on -indev "$iso" -extract /arch/aarch64/airootfs.sfs a.sfs \
  -extract /arch/boot/aarch64/omarchy-live.efi live.efi >/dev/null 2>&1

rm -rf upper merged && mkdir -p lower upper merged
mount -o loop,ro root.img lower
mount -t tmpfs tmpfs upper && mkdir -p upper/u upper/w
mount -t overlay overlay -o lowerdir=lower/omarchy-root,upperdir=upper/u,workdir=upper/w merged
for d in proc sys dev; do mount --rbind /$d merged/$d; done
mount -t tmpfs tmpfs merged/tmp
R=merged
cleanup() { cd /; umount -R $W/merged; umount $W/upper; umount $W/lower; }
trap cleanup EXIT
KVER=$(ls $R/usr/lib/modules | head -1)
echo "target kernel $KVER, container kernel $(uname -r)"

# The offline-mirror packages the installer adds on Snapdragon machines.
rm -rf sfs
unsquashfs -q -f -d sfs a.sfs 'var/cache/omarchy/mirror/offline/systemd-ukify-*' \
  'var/cache/omarchy/mirror/offline/qcom-firmware-extract-*' \
  'var/cache/omarchy/mirror/offline/python-pefile-*' \
  'var/cache/omarchy/mirror/offline/linux-firmware-qcom-*' >/dev/null 2>&1
mkdir -p $R/tmp/pkgs && cp sfs/var/cache/omarchy/mirror/offline/*.pkg.tar.* $R/tmp/pkgs/ && rm -f $R/tmp/pkgs/*.sig
chroot $R sh -c 'pacman -U --noconfirm --nodeps --nodeps /tmp/pkgs/*.pkg.tar.*' >pacman.log 2>&1
chroot $R sh -c 'command -v ukify && command -v qcom-firmware-extract' >/dev/null &&
  pass "ukify and qcom-firmware-extract installed from the offline mirror" || fail "offline packages (see $W/pacman.log)"

# --- 1. device tree pin -------------------------------------------------------
dtbdir=$(ls -d $R/boot/dtbs/linux-omarchy*/qcom | head -1)
[[ -f $dtbdir/x1p64100-microsoft-denali.dtb ]] && pass "target kernel ships x1p64100-microsoft-denali.dtb" || fail "LCD tree missing from the target kernel"
mkdir -p $R/etc/kernel
cat >$R/etc/kernel/uki.conf <<EOF
[UKI]
Cmdline=@/etc/kernel/cmdline
# BEGIN OMARCHY QUALCOMM DEVICE TREES
# Generated by Omarchy for Qualcomm Snapdragon devices.
[UKI]
DeviceTreeAuto=${dtbdir#$R}/x1e80100-microsoft-denali-oled.dtb ${dtbdir#$R}/x1p64100-microsoft-denali.dtb
# END OMARCHY QUALCOMM DEVICE TREES
EOF
echo "root=UUID=0 rw" >$R/etc/kernel/cmdline
cp $P/sp11-lcd-devicetree $R/tmp/
chroot $R bash /tmp/sp11-lcd-devicetree >/dev/null
cp $R/etc/kernel/uki.conf first.conf
chroot $R bash /tmp/sp11-lcd-devicetree >/dev/null
cmp -s first.conf $R/etc/kernel/uki.conf && pass "pin is idempotent" || fail "second run changed uki.conf"
grep -q '^DeviceTreeAuto=' $R/etc/kernel/uki.conf && fail "DeviceTreeAuto survived" || pass "Omarchy's DeviceTreeAuto block removed"
grep -q '^DeviceTree=.*/x1p64100-microsoft-denali.dtb$' $R/etc/kernel/uki.conf && pass "DeviceTree= names the LCD tree" || fail "no LCD DeviceTree= line"
grep -q '^Cmdline=@/etc/kernel/cmdline' $R/etc/kernel/uki.conf && pass "unrelated settings kept" || fail "Cmdline lost"

# --- 2. initramfs drop-in ------------------------------------------------------
cp $P/zz-sp11-lcd.conf $R/etc/mkinitcpio.conf.d/
chroot $R mkinitcpio -k "$KVER" -S autodetect -g /tmp/initramfs.img >mkinitcpio.log 2>&1 &&
  pass "mkinitcpio builds with zz-sp11-lcd.conf" || fail "mkinitcpio failed (see $W/mkinitcpio.log)"
chroot $R lsinitcpio /tmp/initramfs.img >initramfs.list 2>/dev/null
for m in msm dispcc-x1e80100 gpucc-x1e80100 phy-qcom-edp panel-edp phy-qcom-qmp-combo ps883x qrtr \
  qcom_pd_mapper pmic_glink pmic_glink_altmode surface_aggregator surface_aggregator_registry \
  surface_aggregator_hub surface_hid_core surface_hid; do
  grep -qE "/${m//[-_]/[-_]}\.ko(\.[a-z]+)?$" initramfs.list && pass "initramfs has $m" || fail "initramfs lacks $m"
done
mkdir -p $R/tmp/x && chroot $R sh -c 'cd /tmp/x && lsinitcpio -x /tmp/initramfs.img'
grep -rqs '?' $R/tmp/x/etc/modules-load.d/ && fail "a '?' module name reached modules-load.d" || pass "no '?' names in modules-load.d"
grep -q 'gen70500_sqe' initramfs.list && pass "GPU microcode in the initramfs" || fail "GPU microcode missing from the initramfs"

# --- 3. firmware through qcom-firmware-extract -----------------------------------
# A /sys/firmware/devicetree/base made from the LCD tree the ISO itself carries.
rm -rf sections dt && python3 /build/uki-dtb.py split live.efi sections >dtbs.txt
lcd=$(awk -F'\t' '$2 == "microsoft,denali-lcd" { print $1 }' dtbs.txt)
python3 /test/dtb2fs.py "sections/$lcd" dt
mkdir -p $R/tmp/dt && cp -r dt/. $R/tmp/dt/ && cp -r $P $R/tmp/payload
chroot $R env QCOM_FW_DT_ROOT=/tmp/dt qcom-firmware-extract --install --no-rebuild -d /tmp/payload/firmware >firmware.log 2>&1
missing=$(chroot $R env QCOM_FW_DT_ROOT=/tmp/dt qcom-firmware-extract --list-missing 2>&1)
[[ $? -eq 0 && -z $missing ]] && pass "no device-tree firmware missing" || fail "firmware missing: $missing"
for f in Denali/qcadsp8380.mbn Denali/adsp_dtb.mbn Denali/qccdsp8380.mbn Denali/cdsp_dtb.mbn qcdxkmsuc8380.mbn; do
  ls $R/usr/lib/firmware/updates/qcom/x1e80100/microsoft/$f* >/dev/null 2>&1 && pass "installed $f" || fail "not installed: $f"
done
grep -qs 'qcdxkmsuc8380' $R/etc/mkinitcpio.conf.d/qcom-firmware.conf && pass "zap shader listed for the initramfs" || fail "zap shader not listed for the initramfs"

# --- 4. Wi-Fi board data, with the record and checksum apply.sh uses -------------
record=$(sed -n "s/^board_record='\(.*\)'$/\1/p" $P/apply.sh)
sum=$(grep -o -- '--expected-sha256 [0-9a-f]*' $P/apply.sh | cut -d' ' -f2)
bytes=$(grep -o -- '--expected-bytes [0-9]*' $P/apply.sh | cut -d' ' -f2)
chroot $R python3 /tmp/payload/extract-ath12k-board.py --expected-bytes "$bytes" --expected-sha256 "$sum" \
  /usr/lib/firmware/ath12k/WCN7850/hw2.0/board-2.bin "$record" /tmp/board.bin >board.log 2>&1 &&
  pass "Wi-Fi board record extracts from the target's board-2.bin ($bytes bytes, sha256 ${sum:0:12})" || fail "Wi-Fi board record (see $W/board.log)"
strings -n 20 $R/usr/lib/firmware/ath12k/WCN7850/hw2.0/board-2.bin | grep -q 'subsystem-device=1107,qmi-chip-id=2,qmi-board-id=255' &&
  echo "NOTE: board-2.bin now has an exact 1107/255 entry; board.bin is no longer needed" ||
  pass "board-2.bin has no 1107/255 entry, so ath12k falls back to board.bin"

# --- 5. the UKI the pinned uki.conf produces ---------------------------------------
# limine-mkinitcpio builds it this way (limine-mkinitcpio-install, build_uki):
# mkinitcpio --kernel --cmdline --uki, which calls ukify without --config.
chroot $R mkinitcpio --kernel "$KVER" --cmdline /etc/kernel/cmdline --uki /tmp/real.efi -S autodetect >uki.log 2>&1 ||
  fail "mkinitcpio --uki (see $W/uki.log)"
python3 /build/uki-dtb.py check $R/tmp/real.efi microsoft,denali-lcd && pass "UKI built like limine-mkinitcpio boots microsoft,denali-lcd" || fail "UKI check"

echo
echo "failures: $failures"
exit $((failures > 0))
